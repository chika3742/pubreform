// Generates the E2E test project: pubspec.yaml, pubspec.lock and .github/pubreform.yaml (detailed design §17.1, §17.2).
// The lockfile is resolved by real `dart pub get` against the fixture registry, with every package at 1.0.0,
// and its URLs are then rewritten to https://pub.dev, as pubreform expects of a real project.
//
// As a script (GitHub E2E): bun test/e2e/make-project.ts <output dir>
import { execFile } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { promisify } from 'node:util'
import { type Fixtures, defaultFixtures, startFixtureServer } from './fixtures.ts'

const run = promisify(execFile)

export const DEPENDENCIES = ['fx_b', 'fx_fresh', 'fx_ignored', 'fx_major', 'fx_needs_b', 'fx_patch', 'fx_sdk']
export const DEV_DEPENDENCIES = ['fx_minor']

export const CONFIG = `# Generated by pubreform test/e2e/make-project.ts.
schedule:
  cron: "* * * * *"
min_release_age_days: 3
labels: [dependencies]
ignore:
  - name: fx_ignored
`

function pubspec(constraint: string): string {
  const deps = (names: string[]) => names.map((n) => `  ${n}: ${constraint}\n`).join('')
  return `# Generated by pubreform test/e2e/make-project.ts.
name: pubreform_e2e
description: Test project for pubreform.
publish_to: none
environment:
  sdk: ^3.0.0
dependencies:
${deps(DEPENDENCIES)}dev_dependencies:
${deps(DEV_DEPENDENCIES)}`
}

export interface ProjectFiles {
  'pubspec.yaml': string
  'pubspec.lock': string
  '.github/pubreform.yaml': string
}

/** Resolves the project against a fixture registry started for this call. */
export async function makeProject(opts: { dart?: string; fixtures?: Fixtures } = {}): Promise<ProjectFiles> {
  const registry = await startFixtureServer({ fixtures: opts.fixtures ?? defaultFixtures() })
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'pubreform-project-'))
  try {
    const env = { ...process.env, PUB_HOSTED_URL: registry.url, PUB_CACHE: path.join(tmp, 'pub-cache') }
    const dir = path.join(tmp, 'project')
    fs.mkdirSync(dir)
    const pub = async (text: string) => {
      fs.writeFileSync(path.join(dir, 'pubspec.yaml'), text)
      await run(opts.dart ?? 'dart', ['pub', 'get'], { cwd: dir, env })
    }
    // Lock every package at 1.0.0, then relax the constraints; pub get keeps the lock.
    await pub(pubspec('1.0.0'))
    const final = pubspec('^1.0.0')
    await pub(final)
    const lock = fs
      .readFileSync(path.join(dir, 'pubspec.lock'), 'utf8')
      .replaceAll(`url: "${registry.url}"`, 'url: "https://pub.dev"')
    return { 'pubspec.yaml': final, 'pubspec.lock': lock, '.github/pubreform.yaml': CONFIG }
  } finally {
    await registry.close()
    fs.rmSync(tmp, { recursive: true, force: true })
  }
}

export function writeProject(dir: string, files: ProjectFiles) {
  for (const [name, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(dir, name)), { recursive: true })
    fs.writeFileSync(path.join(dir, name), content)
  }
}

if (import.meta.main) {
  const out = process.argv[2]
  if (!out) {
    console.error('usage: bun test/e2e/make-project.ts <output dir>')
    process.exit(2)
  }
  writeProject(out, await makeProject())
}
