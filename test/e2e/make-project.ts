// Generates the E2E test projects: pubspec.yaml, pubspec.lock and .github/pubreform.yaml (and the workspace members).
// The lockfile is resolved by real `dart pub get` against the fixture registry, with every package at 1.0.0,
// and its URLs are then rewritten to https://pub.dev, as pubreform expects of a real project.
//
// As a script (GitHub E2E): bun test/e2e/make-project.ts <output dir>
import { execFile } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { promisify } from 'node:util'
import { type Fixtures, defaultFixtures, startFixtureServer } from './fixtures.ts'

const run = promisify(execFile)

export const DEPENDENCIES = [
  'fx_b',
  'fx_fresh',
  'fx_ignored',
  'fx_late',
  'fx_major',
  'fx_needs_b',
  'fx_needs_pinned',
  'fx_parent',
  'fx_patch',
  'fx_pinned',
  'fx_pinned_dep',
  'fx_sdk',
  'fx_vuln',
]
export const DEV_DEPENDENCIES = ['fx_minor']
/** Dependencies pinned to 1.0.0 instead of ^1.0.0. */
export const PINNED = ['fx_pinned', 'fx_pinned_dep']

export const CONFIG = `# Generated by pubreform test/e2e/make-project.ts.
schedule:
  cron: "* * * * *"
min_release_age_days: 3
labels: [dependencies]
ignore:
  - name: fx_ignored
`

/**
 * post_update commands that generate files, and try to reach what they must not (the tokens, the network, ...).
 * PROBE_URL, if set, is the URL to connect to instead of GITHUB_API_URL (in the local E2E, the host as seen from a
 * container). PROBE_HOME is the runner's home, with the file pubreform-probe-secret that the commands must not see.
 */
export const POST_UPDATE_CONFIG = `${CONFIG}post_update:
  - run: dart run tool/gen.dart
  - run: sh tool/probe.sh
    env: [GITHUB_API_URL, GITHUB_WORKSPACE, RUNNER_TEMP, PROBE_URL, PROBE_HOME]
  - run: sh tool/network.sh
    network: true
    env: [GITHUB_API_URL, PROBE_URL]
`

/** The file in the runner's home that the post_update commands must not see. */
export const PROBE_SECRET = 'pubreform-probe-secret'

/** Files that the post_update commands of POST_UPDATE_CONFIG use. */
export const POST_UPDATE_FILES: Record<string, string> = {
  '.gitignore': '.dart_tool/\nbuild/\n',
  'obsolete.g.dart': '// Deleted by tool/probe.sh.\n',
  // Runs without the network: no implicit pub get may start.
  'tool/gen.dart': `import 'dart:io';

void main() {
  final lock = File('pubspec.lock').readAsStringSync();
  final entry = RegExp(r'^  (fx_\\w+):\\n(?:    .*\\n)*?    version: "([^"]+)"', multiLine: true);
  final lines = [for (final m in entry.allMatches(lock)) "  '\${m[1]}': '\${m[2]}',"]..sort();
  Directory('lib').createSync();
  File('lib/versions.g.dart').writeAsStringSync('const versions = {\\n\${lines.join('\\n')}\\n};\\n');
}
`,
  'tool/probe.sh': `# Tries what a post_update command must not be able to do, and records the results in probe.txt.
out=probe.txt
url=\${PROBE_URL:-$GITHUB_API_URL}
echo "token: \${INPUT_TOKEN:-unset}" > "$out"
hits=0
for f in /proc/[0-9]*/environ; do
  if (tr '\\000' '\\n' < "$f") 2> /dev/null | grep -q -e '^INPUT_TOKEN=' -e '^ACTIONS_RUNTIME_TOKEN=' -e '^GH_TOKEN='; then hits=$((hits + 1)); fi
done
echo "environ with tokens: $hits" >> "$out"
if [ -n "$(pgrep -f dist/main.js)" ]; then echo "pubreform process: visible" >> "$out"; else echo "pubreform process: not visible" >> "$out"; fi
if curl -sS --max-time 10 -o /dev/null "$url" 2> /dev/null; then echo "network: ok" >> "$out"; else echo "network: failed" >> "$out"; fi
if [ -e .git ]; then echo ".git: present" >> "$out"; else echo ".git: absent" >> "$out"; fi
for d in RUNNER_TEMP GITHUB_WORKSPACE; do
  eval "p=\\\${$d}"
  if [ -n "$p" ] && [ -e "$p" ]; then echo "$d: present" >> "$out"; else echo "$d: absent" >> "$out"; fi
done
if [ -e "$PROBE_HOME/${PROBE_SECRET}" ]; then echo "runner home: visible" >> "$out"; else echo "runner home: not visible" >> "$out"; fi
if touch "$PUB_CACHE/pubreform-probe" 2> /dev/null; then echo "pub cache: writable" >> "$out"; else echo "pub cache: read-only" >> "$out"; fi
sdk=$(dirname "$(readlink -f "$(command -v dart)")")
if touch "$sdk/pubreform-probe" 2> /dev/null; then echo "sdk: writable" >> "$out"; else echo "sdk: read-only" >> "$out"; fi
printf 'a\\000b' > blob.bin
printf '#!/bin/sh\\n' > run.sh
chmod +x run.sh
ln -s /etc/passwd passwd-link
rm obsolete.g.dart
mkdir -p build
echo ignored > build/ignored.txt
echo '# changed by post_update' >> pubspec.yaml
# Left running: it must stop with the container.
sleep 600 > /dev/null 2>&1 &
`,
  'tool/network.sh': `if curl -sS --max-time 10 -o /dev/null "\${PROBE_URL:-$GITHUB_API_URL}"; then echo ok > network-on.txt; else echo failed > network-on.txt; fi
`,
}

/** What tool/probe.sh records when nothing that it tries works. */
export const PROBE_RESULT = [
  'token: unset',
  'environ with tokens: 0',
  'pubreform process: not visible',
  'network: failed',
  '.git: absent',
  'RUNNER_TEMP: absent',
  'GITHUB_WORKSPACE: absent',
  'runner home: not visible',
  'pub cache: read-only',
  'sdk: read-only',
]

/** The member of the project made with `workspace`. It declares fx_major too. */
export const MEMBER_PUBSPEC = 'pkgs/member/pubspec.yaml'

function pubspecs(constraint: string, workspace: boolean): Record<string, string> {
  const deps = (names: string[]) => names.map((n) => `  ${n}: ${PINNED.includes(n) ? '1.0.0' : constraint}\n`).join('')
  const root = `# Generated by pubreform test/e2e/make-project.ts.
name: pubreform_e2e
description: Test project for pubreform.
publish_to: none
environment:
  sdk: ${workspace ? '^3.6.0' : '^3.0.0'}
${workspace ? 'workspace:\n  - pkgs/member\n' : ''}dependencies:
${deps(DEPENDENCIES)}dev_dependencies:
${deps(DEV_DEPENDENCIES)}`
  if (!workspace) return { 'pubspec.yaml': root }
  const member = `# Generated by pubreform test/e2e/make-project.ts.
name: member
publish_to: none
environment:
  sdk: ^3.6.0
resolution: workspace
dependencies:
  fx_major: ${constraint}
`
  return { 'pubspec.yaml': root, [MEMBER_PUBSPEC]: member }
}

export interface ProjectFiles {
  'pubspec.yaml': string
  'pubspec.lock': string
  '.github/pubreform.yaml': string
  [file: string]: string
}

/**
 * Resolves the project against a fixture registry started for this call.
 * With `postUpdate`, the config has POST_UPDATE_CONFIG and the project has POST_UPDATE_FILES.
 * With `workspace`, the root is a pub workspace with the member MEMBER_PUBSPEC.
 */
export async function makeProject(
  opts: { dart?: string; fixtures?: Fixtures; postUpdate?: boolean; workspace?: boolean } = {},
): Promise<ProjectFiles> {
  const registry = await startFixtureServer({ fixtures: opts.fixtures ?? defaultFixtures() })
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'pubreform-project-'))
  try {
    const env = { ...process.env, PUB_HOSTED_URL: registry.url, PUB_CACHE: path.join(tmp, 'pub-cache') }
    const dir = path.join(tmp, 'project')
    const pub = async (files: Record<string, string>) => {
      writeProject(dir, files)
      await run(opts.dart ?? 'dart', ['pub', 'get'], { cwd: dir, env })
    }
    // Lock every package at 1.0.0, then relax the constraints; pub get keeps the lock.
    const workspace = opts.workspace ?? false
    await pub(pubspecs('1.0.0', workspace))
    const final = pubspecs('^1.0.0', workspace)
    await pub(final)
    const lock = fs
      .readFileSync(path.join(dir, 'pubspec.lock'), 'utf8')
      .replaceAll(`url: "${registry.url}"`, 'url: "https://pub.dev"')
    const files = { ...final, 'pubspec.yaml': final['pubspec.yaml']!, 'pubspec.lock': lock, '.github/pubreform.yaml': CONFIG }
    return opts.postUpdate ? { ...files, ...POST_UPDATE_FILES, '.github/pubreform.yaml': POST_UPDATE_CONFIG } : files
  } finally {
    await registry.close()
    fs.rmSync(tmp, { recursive: true, force: true })
  }
}

/** The pubspec.yaml files of the workspace project, with `constraint` on every fixture dependency. */
function workspacePubspecs(constraint: string): Record<string, string> {
  const header = (name: string) => `# Generated by pubreform test/e2e/make-project.ts.
name: ${name}
publish_to: none
environment:
  sdk: ^3.11.0
`
  return {
    'pubspec.yaml': `${header('pubreform_e2e_workspace')}workspace:
  - pkgs/*
`,
    'pkgs/a/pubspec.yaml': `${header('a')}resolution: workspace
dependencies:
  fx_patch: ${constraint}
  # Declared in both members.
  fx_major: ${constraint}
`,
    'pkgs/b/pubspec.yaml': `${header('b')}resolution: workspace
dependencies:
  a: any
  fx_minor: ${constraint}
dev_dependencies:
  fx_major:
    version: ${constraint}
dependency_overrides:
  fx_minor: 1.0.0
`,
  }
}

/** A pub workspace with the members pkgs/a and pkgs/b, resolved like makeProject. */
export async function makeWorkspace(opts: { dart?: string } = {}): Promise<ProjectFiles> {
  const registry = await startFixtureServer({ fixtures: defaultFixtures() })
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'pubreform-workspace-'))
  try {
    const env = { ...process.env, PUB_HOSTED_URL: registry.url, PUB_CACHE: path.join(tmp, 'pub-cache') }
    const dir = path.join(tmp, 'project')
    const pub = async (files: Record<string, string>) => {
      writeProject(dir, files)
      await run(opts.dart ?? 'dart', ['pub', 'get'], { cwd: dir, env })
    }
    await pub(workspacePubspecs('1.0.0'))
    const final = workspacePubspecs('^1.0.0')
    await pub(final)
    const lock = fs
      .readFileSync(path.join(dir, 'pubspec.lock'), 'utf8')
      .replaceAll(`url: "${registry.url}"`, 'url: "https://pub.dev"')
    return { ...final, 'pubspec.yaml': final['pubspec.yaml']!, 'pubspec.lock': lock, '.github/pubreform.yaml': CONFIG }
  } finally {
    await registry.close()
    fs.rmSync(tmp, { recursive: true, force: true })
  }
}

export function writeProject(dir: string, files: Record<string, string>) {
  for (const [name, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(dir, name)), { recursive: true })
    fs.writeFileSync(path.join(dir, name), content)
  }
}

if (import.meta.main) {
  const out = process.argv[2]
  if (!out) {
    console.error('usage: bun test/e2e/make-project.ts <output dir>')
    process.exit(2)
  }
  writeProject(out, await makeProject())
}
